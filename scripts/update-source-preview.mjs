/**
 * Refresh the static Arduino code viewer after editing the sketch.
 * Run from the project folder: node scripts/update-source-preview.mjs
 * This helper uses Node's standard library; the deployed website needs no build step.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Resolving against this script keeps the command independent of the terminal folder.
const projectDirectory = new URL("../projects/robotic-arm/", import.meta.url);
const sketchUrl = new URL("ROBOTIC_ARM_COLOR_SORTING.ino", projectDirectory);
const outputUrl = new URL("index.html", projectDirectory);
const sketch = await readFile(sketchUrl, "utf8");

// Escape source code as text so C++ symbols cannot become HTML tags in the viewer.
const entities = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
const escapedSketch = sketch.replace(/[&<>"']/g, (character) => entities[character]);

const page = `<!doctype html>
<html lang="en">
  <head>
    <!-- Generated by scripts/update-source-preview.mjs; edit the sketch and rerun it. -->
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="color-scheme" content="dark" />
    <meta name="theme-color" content="#0b0d14" />
    <meta name="description" content="Arduino source code for the Automated Pill Color Sorting Robotic Arm project." />
    <title>Robotic Arm Source Code | Bryan C. Tumazar</title>
    <link rel="icon" type="image/svg+xml" href="../../assets/favicon.svg" />
    <link rel="stylesheet" href="../../styles.css" />
  </head>
  <body>
    <a class="skip-link" href="#main-content">Skip to source code</a>
    <main class="container source-page" id="main-content">
      <a class="source-back" href="../../index.html#projects">Back to portfolio</a>
      <p class="section-kicker">ROBOTIC ARM / SOURCE CODE</p>
      <h1>Automated Pill Color Sorting Robotic Arm</h1>
      <p class="source-description">Arduino sketch for color sensing and servo control, using a TCS34725 color sensor, PCA9685 servo driver, and I2C LCD.</p>
      <!-- The download points to the actual sketch, rather than a copy of the HTML page. -->
      <div class="source-toolbar">
        <p class="source-filename" id="source-filename">ROBOTIC_ARM_COLOR_SORTING.ino</p>
        <a class="btn btn-primary" href="ROBOTIC_ARM_COLOR_SORTING.ino" download>Download .ino</a>
      </div>
      <!-- Escaped code is visible text. No portfolio JavaScript is needed on this page. -->
      <pre class="source-code" aria-labelledby="source-filename"><code>${escapedSketch}</code></pre>
    </main>
  </body>
</html>
`;

await writeFile(outputUrl, page, "utf8");
console.log(`Updated ${fileURLToPath(outputUrl)}`);
